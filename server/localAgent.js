function modifyExisting(prompt, files) {
  const p = prompt.toLowerCase();
  const next = files.map((f) => ({ ...f }));
  const css = next.find((f) => f.path.endsWith(".css"));
  const html = next.find((f) => f.path.endsWith(".html"));
  const js = next.find((f) => f.path.endsWith(".js") || f.path.endsWith(".jsx") || f.path.endsWith(".py"));
  const changed = [];

  if (css && /(dark|theme|color|mint|background)/.test(p)) {
    if (/light/.test(p)) {
      css.content = css.content
        .replace(/#07090d/g, "#f4f1ea")
        .replace(/#e8eef8/g, "#16181d");
    } else {
      css.content += `\nbody { filter: saturate(1.05); }\n`;
    }
    changed.push(css.path);
  }
  if (html && /(title|heading|rename|brand)/.test(p)) {
    const t = titleFrom(prompt);
    html.content = html.content.replace(/<h1>[^<]*<\/h1>/, `<h1>${esc(t)}</h1>`);
    changed.push(html.path);
  }
  if (js && /(comment|document|explain)/.test(p)) {
    js.content = `// Updated by Corex Code agent\n` + js.content;
    changed.push(js.path);
  }
  if (!changed.length) {
    const readme = next.find((f) => f.path === "README.md");
    const extra = `\n\n## Agent note\n\nFollow-up: ${prompt}\n`;
    if (readme) {
      readme.content += extra;
      changed.push("README.md");
    } else {
      next.push({ path: "NOTES.md", content: `# Follow-up\n\n${prompt}\n` });
      changed.push("NOTES.md");
    }
  }
  return {
    files: next,
    summary: `Applied follow-up edits (${changed.join(", ")}). Ask for a more specific file change if you want a deeper rewrite.`,
  };
}

export function localGenerate({ prompt, files = [] }) {
  const p = prompt.toLowerCase();
  const title = titleFrom(prompt);
  const hasFiles = files.some((f) => f.content && f.content.length > 20);

  if (hasFiles && /(change|update|fix|refactor|improve|dark|light|rename|add |make )/i.test(prompt)) {
    return modifyExisting(prompt, files);
  }
  if (/(gomoku|five in a row|五子)/.test(p)) return gomoku(title);
  if (/(snake)/.test(p)) return snakeGame(title);
  if (/(todo|task list|checklist)/.test(p)) return todoApp(title);
  if (/(dashboard|analytics|metrics)/.test(p)) return dashboard(title);
  if (/(express|rest api|endpoint)/.test(p)) return restApi(title);
  if (/(react component|jsx)/.test(p)) return reactComponent(title);
  if (/(python|django|flask|script)/.test(p)) return pythonScript(title, prompt);
  if (/(landing|marketing|website|homepage|portfolio)/.test(p)) return landingPage(title, prompt);
  if (/(game)/.test(p)) return snakeGame(title);
  return genericWeb(title, prompt);
}

