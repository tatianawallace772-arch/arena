function titleFrom(prompt) {
  const cleaned = prompt.replace(/["'`]/g, " ").replace(/\s+/g, " ").trim();
  const m = cleaned.match(
    /(?:called|named|for|titled)\s+([A-Z][\w\s-]{1,40})/i
  );
  if (m) return m[1].trim();
  const words = cleaned
    .replace(
      /^(please |can you |could you |create |build |make |write |generate |design |implement |add )/gi,
      ""
    )
    .split(" ")
    .slice(0, 4)
    .join(" ");
  if (words.length > 2 && words.length < 32) {
    return words.replace(/\b\w/g, (c) => c.toUpperCase());
  }
  return "Corex App";
}

function slug(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 32) || "app";
}

function esc(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

