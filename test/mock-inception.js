'use strict';
/*
 * A mock of the Inception Labs (OpenAI-compatible) streaming API.
 * Used to prove the agent loop end-to-end without network access.
 *
 *   node test/mock-inception.js 4010
 *
 * Then start the app with:
 *   INCEPTION_BASE_URL=http://127.0.0.1:4010/v1 node server/index.js
 */

const http = require('http');

const PORT = Number(process.argv[2] || 4010);

// Scripted conversation, keyed by how many assistant turns have happened.
const SCRIPT = [
  // Turn 1: explore the project
  {
    text: 'Let me look at the project structure first.',
    toolCalls: [{ name: 'list_dir', arguments: { path: '.', depth: 1 } }],
  },
  // Turn 2: read a file
  {
    text: 'Now let me check the notes file.',
    toolCalls: [{ name: 'read_file', arguments: { path: 'sandbox-notes.txt' } }],
  },
  // Turn 3: write a file
  {
    text: 'I will write the summary file.',
    toolCalls: [
      {
        name: 'write_file',
        arguments: {
          path: 'sandbox-summary.md',
          content: '# Summary\n\nGenerated by the agent loop test.\n',
        },
      },
    ],
  },
  // Turn 4: run a command
  {
    text: 'Verifying the file exists.',
    toolCalls: [{ name: 'run_command', arguments: { command: 'cat sandbox-summary.md && wc -l sandbox-summary.md' } }],
  },
  // Turn 5: git
  {
    text: 'Checking git state.',
    toolCalls: [{ name: 'git_status', arguments: {} }],
  },
  // Turn 6: finish
  {
    text: 'Done.',
    toolCalls: [
      {
        name: 'finish',
        arguments: { summary: 'Created sandbox-summary.md and verified it.', status: 'completed' },
      },
    ],
  },
];

function sse(res, obj) {
  res.write(`data: ${JSON.stringify(obj)}\n\n`);
}

function chunk(delta, finishReason = null) {
  return {
    id: 'chatcmpl-mock',
    object: 'chat.completion.chunk',
    created: Math.floor(Date.now() / 1000),
    model: 'mercury-coder',
    choices: [{ index: 0, delta, finish_reason: finishReason }],
  };
}

const server = http.createServer((req, res) => {
  if (req.url.startsWith('/v1/models')) {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ object: 'list', data: [{ id: 'mercury-coder' }, { id: 'mercury-2' }] }));
    return;
  }

  if (req.url.startsWith('/v1/chat/completions') && req.method === 'POST') {
    let body = '';
    req.on('data', (c) => (body += c));
    req.on('end', async () => {
      let payload = {};
      try {
        payload = JSON.parse(body);
      } catch {
        res.writeHead(400).end('bad json');
        return;
      }
      const messages = payload.messages || [];

      // How many assistant turns have already happened?
      const assistantTurns = messages.filter((m) => m.role === 'assistant').length;
      const step = SCRIPT[Math.min(assistantTurns, SCRIPT.length - 1)];

      // A request with no tools means the caller wants a plain answer.
      const wantsTools = Array.isArray(payload.tools) && payload.tools.length > 0;

      res.writeHead(200, {
        'Content-Type': 'text/event-stream',
        'Cache-Control': 'no-cache',
        Connection: 'keep-alive',
      });

      // Stream the text token by token.
      const words = (step.text || '').match(/\S+\s*/g) || [];
      for (const w of words) {
        sse(res, chunk({ content: w }));
        await new Promise((r) => setTimeout(r, 6));
      }

      if (wantsTools && step.toolCalls?.length) {
        for (let i = 0; i < step.toolCalls.length; i++) {
          const tc = step.toolCalls[i];
          const args = JSON.stringify(tc.arguments);
          // Emit the function name and arguments in fragments, like real APIs do.
          sse(res, chunk({ tool_calls: [{ index: i, id: `call_${assistantTurns}_${i}`, type: 'function', function: { name: tc.name, arguments: '' } }] }));
          const mid = Math.floor(args.length / 2);
          sse(res, chunk({ tool_calls: [{ index: i, function: { arguments: args.slice(0, mid) } }] }));
          sse(res, chunk({ tool_calls: [{ index: i, function: { arguments: args.slice(mid) } }] }));
        }
        sse(res, chunk({}, 'tool_calls'));
      } else {
        sse(res, chunk({}, 'stop'));
      }

      sse(res, {
        id: 'chatcmpl-mock',
        object: 'chat.completion.chunk',
        choices: [],
        usage: { prompt_tokens: 120, completion_tokens: 40, total_tokens: 160 },
      });
      res.write('data: [DONE]\n\n');
      res.end();
    });
    return;
  }

  res.writeHead(404).end('not found');
});

server.listen(PORT, '127.0.0.1', () => {
  console.log(`mock inception api on http://127.0.0.1:${PORT}/v1`);
});
