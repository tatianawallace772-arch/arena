'use strict';
/*
 * End-to-end test of the agent loop against the mock Inception API.
 * Verifies streaming text, tool-call accumulation, real file writes,
 * real command execution, git tools and the finish handshake.
 *
 * Requires: mock API on :4010 and the app on :3001 with
 *   INCEPTION_BASE_URL=http://127.0.0.1:4010/v1
 */

const WebSocket = require('ws');
const fs = require('fs');
const path = require('path');
const assert = require('assert');

const APP = process.env.APP_URL || 'http://127.0.0.1:3001';
const ROOT = path.resolve(__dirname, '..');

(async () => {
  // The mock agent reads this fixture, so make sure it exists.
  const notesPath = path.join(ROOT, 'sandbox-notes.txt');
  const notes = 'These are sandbox notes used by the agent loop test.\nLine two.\n';
  fs.writeFileSync(notesPath, notes);

  const results = [];
  const check = (name, cond, extra = '') => results.push({ name, ok: !!cond, extra });

  const events = [];
  await new Promise((resolve, reject) => {
    const socket = new WebSocket(`${APP.replace('http', 'ws')}/ws/agent?session=e2e-${Date.now()}`);
    const timer = setTimeout(() => {
      socket.close();
      reject(new Error('agent turn timed out'));
    }, 60000);

    socket.on('open', () => {
      socket.on('message', (raw) => {
        const msg = JSON.parse(raw.toString());
        if (msg.type === 'ready') {
          socket.send(JSON.stringify({ type: 'chat', message: 'Create a summary file for me' }));
        } else if (msg.type === 'agent_event') {
          events.push(msg.event);
          if (msg.event.type === 'turn_end' || (msg.event.type === 'error' && !msg.event.recoverable)) {
            clearTimeout(timer);
            setTimeout(() => socket.close(), 150);
            resolve();
          }
        }
      });
    });
    socket.on('error', reject);
  });

  const types = events.map((e) => e.type);
  const toolCalls = events.filter((e) => e.type === 'tool_call');
  const toolResults = events.filter((e) => e.type === 'tool_result');
  const text = events.filter((e) => e.type === 'text_delta').map((e) => e.text).join('');

  check('no agent error events', !types.includes('error'),
    JSON.stringify(events.filter((e) => e.type === 'error')));
  check('turn_started and turn_ended', types.includes('turn_start') && types.includes('turn_end'));
  check('streamed assistant text', text.length > 10, JSON.stringify(text.slice(0, 120)));
  check('multiple tool calls executed', toolCalls.length >= 5, `count=${toolCalls.length} ${JSON.stringify(toolCalls.map(t=>t.tool))}`);
  check('every tool call got a result', toolResults.length === toolCalls.length,
    `${toolCalls.length} calls / ${toolResults.length} results`);
  check('list_dir ran', toolCalls.some((c) => c.tool === 'list_dir'));
  check('read_file ran', toolCalls.some((c) => c.tool === 'read_file'));
  check('write_file ran', toolCalls.some((c) => c.tool === 'write_file'));
  check('run_command ran', toolCalls.some((c) => c.tool === 'run_command'));
  check('git_status ran', toolCalls.some((c) => c.tool === 'git_status'));
  check('finish tool ran', toolCalls.some((c) => c.tool === 'finish'));

  const runResult = toolResults.find((r) => r.tool === 'run_command');
  check('command output returned to the model',
    runResult && runResult.output.includes('Generated by the agent loop test'),
    runResult ? runResult.output.slice(0, 200) : 'missing');

  const readResult = toolResults.find((r) => r.tool === 'read_file');
  check('read_file returned numbered content',
    readResult && /^\s*1\|/m.test(readResult.output),
    readResult ? readResult.output.slice(0, 120) : 'missing');

  check('usage reported', events.some((e) => e.type === 'usage'));
  check('finish summary surfaced', events.some((e) => e.type === 'finish'));

  // The agent should have really touched the filesystem.
  const summaryPath = path.join(ROOT, 'sandbox-summary.md');
  check('agent actually wrote sandbox-summary.md', fs.existsSync(summaryPath),
    'file missing on disk');
  if (fs.existsSync(summaryPath)) {
    const content = fs.readFileSync(summaryPath, 'utf8');
    check('written file has expected content', content.includes('Generated by the agent loop test'));
    fs.unlinkSync(summaryPath);
  }

  fs.rmSync(notesPath, { force: true });

  let failed = 0;
  console.log('\nAgent loop end-to-end (mock Inception API)\n');
  for (const r of results) {
    console.log(`  ${r.ok ? '✓' : '✗'} ${r.name}${r.ok ? '' : `\n      ${r.extra}`}`);
    if (!r.ok) failed++;
  }
  console.log(`\n  ${results.length - failed} passed, ${failed} failed\n`);
  process.exit(failed ? 1 : 0);
})().catch((err) => {
  console.error('E2E harness error:', err.message);
  process.exit(1);
});
